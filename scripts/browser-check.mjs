// Optional browser QA. Requires Playwright and an installed Chromium browser.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtempSync, mkdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { unzip, zip } from '../lib/archive.mjs';

const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const data = mkdtempSync(join(tmpdir(), 'opslands-browser-')), port = 41000 + Math.floor(Math.random() * 1000);
const server = spawn(process.execPath, ['server.mjs'], { env: { ...process.env, PORT: String(port), OPSLANDS_DATA: data }, stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
try {
  await new Promise((resolve, reject) => { server.stdout.on('data', d => String(d).includes('OPSLands:') && resolve()); server.on('error', reject); server.once('exit', c => reject(new Error(`Server exit ${c}`))); });
  browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${port}`);
  await page.locator('#login-form [name=name]').fill('QA Admin');
  await page.locator('#login-form [name=login]').fill('qa.admin');
  await page.locator('#login-form [name=password]').fill('test-password');
  await page.getByRole('button', { name: 'Создать и войти' }).click();
  await page.locator('.card').first().waitFor();
  assert.equal(await page.locator('.card').count(), 3);
  mkdirSync('data/qa', { recursive: true });
  await page.screenshot({ path: 'data/qa/catalog-desktop.png', fullPage: true });
  await page.locator('#search').fill('Editorial'); assert.equal(await page.locator('.card').count(), 1);
  await page.locator('[data-build]').click();
  await page.locator('[name=action]').fill('https://example.com/submit');
  await page.locator('[data-key=offer_id]').fill('qa-123');
  await page.screenshot({ path: 'data/qa/build-desktop.png', fullPage: true });
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Скачать ZIP', exact: true }).click();
  const download = await pending;
  const files = unzip(readFileSync(await download.path()));
  assert.ok(Buffer.from(files['index.html'], 'base64').toString().includes('value="qa-123"'));
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.locator('[data-edit]').click();
  await page.locator('#edit-form [name=name]').fill('QA variation');
  await page.getByRole('button', { name: 'Сохранить новую версию', exact: true }).click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.locator('[data-view=mine]').click(); await page.getByRole('heading', { name: 'QA variation' }).waitFor();
  await page.locator('[data-view=partners]').click();
  await page.locator('#add-main').click();
  await page.locator('#partner-form [name=name]').fill('QA Partner');
  await page.getByRole('button', { name: 'Сохранить профиль', exact: true }).click();
  await page.locator('#modal').waitFor({ state: 'hidden' }); await page.getByRole('heading', { name: 'QA Partner' }).waitFor();
  await page.locator('[data-view=admin]').click();
  await page.locator('#admin-search').waitFor();
  await page.locator('#add-main').click();
  await page.locator('#user-form [name=name]').fill('QA Member');
  await page.locator('#user-form [name=login]').fill('qa.member');
  await page.locator('#user-form [name=password]').fill('member-password');
  await page.locator('#user-form').getByRole('button', { name: 'Создать пользователя', exact: true }).click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.locator('.admin-table').first().getByText('QA Member', { exact: true }).waitFor();
  await page.screenshot({ path: 'data/qa/admin-desktop.png', fullPage: true });
  const member = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  member.on('pageerror', e => errors.push(e.message));
  await member.goto(`http://127.0.0.1:${port}`);
  await member.locator('#login-form [name=login]').fill('qa.member');
  await member.locator('#login-form [name=password]').fill('member-password');
  await member.getByRole('button', { name: 'Войти', exact: true }).click();
  await member.locator('.card').first().waitFor();
  assert.equal(await member.locator('.card').count(), 3, 'Member sees admin private variation');
  assert.equal(await member.locator('#admin-nav').isVisible(), false);
  await member.locator('#add-main').click();
  await member.locator('#edit-form [name=name]').fill('Member private');
  const privateHtml = '<html><head><link rel="stylesheet" href="assets/private.css"></head><body><form action="{{form_action}}" method="{{form_method}}">{{hidden_fields}}<input name="name"><input name="phone"></form></body></html>';
  await member.locator('#upload').setInputFiles({ name: 'member.zip', mimeType: 'application/zip', buffer: zip({ 'index.html': Buffer.from(privateHtml).toString('base64'), 'assets/private.css': Buffer.from('body{color:rgb(12,34,56)}').toString('base64') }) });
  await member.locator('#edit-form').getByRole('button', { name: 'Добавить в библиотеку', exact: true }).click();
  await member.locator('#modal').waitFor({ state: 'hidden' });
  const privateCard = member.locator('.card').filter({ has: member.getByRole('heading', { name: 'Member private' }) });
  await privateCard.waitFor();
  await privateCard.scrollIntoViewIfNeeded();
  const frame = privateCard.frameLocator('iframe');
  await frame.locator('body').waitFor();
  await frame.locator('body').evaluate(async () => { if (document.readyState !== 'complete') await new Promise(resolve => window.addEventListener('load', resolve)); });
  assert.equal(await frame.locator('body').evaluate(el => getComputedStyle(el).color), 'rgb(12, 34, 56)', 'Private preview assets fail authentication');
  await page.locator('#admin-search').fill('Member private');
  // Refresh the admin list to include the member's newly uploaded private landing.
  await page.locator('[data-view=admin]').click(); await page.locator('#admin-search').waitFor();
  await page.locator('#admin-search').fill('Member private');
  await page.locator('#admin-landings').getByText('Member private', { exact: true }).waitFor();
  await page.locator('.admin-table').first().locator('tr').filter({ hasText: 'QA Member' }).getByRole('button', { name: 'Удалить', exact: true }).click();
  await page.getByRole('button', { name: 'Удалить пользователя', exact: true }).click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await member.reload(); await member.locator('#login-form').waitFor();
  await member.close();
  await page.reload(); await page.locator('.card').first().waitFor();
  assert.equal(await page.locator('#auth-root').isVisible(), false, 'Session lost on reload');
  await page.locator('[data-view=catalog]').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'data/qa/catalog-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page overflows');
  await page.locator('[data-build]').first().click();
  await page.screenshot({ path: 'data/qa/build-mobile.png', fullPage: true });
  assert.ok(await page.locator('#modal').evaluate(el => el.scrollWidth <= el.clientWidth), 'Mobile modal overflows');
  assert.deepEqual(errors, []);
  console.log('Browser QA passed: setup, persistent login, admin user creation, search, preview, ZIP download, version, partner, mobile; no JS errors.');
} finally {
  await browser?.close(); if (server.exitCode === null) { const done = once(server, 'exit'); server.kill(); await done; }
  rmSync(data, { recursive: true, force: true });
}
